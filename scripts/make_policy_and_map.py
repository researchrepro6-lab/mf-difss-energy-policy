# ---------------------------------------------------------------- world map
# Robinson projection implemented directly (standard Robinson table, linear interpolation),
# so the map needs only numpy and matplotlib (no geopandas or pyproj).
import json
from matplotlib.collections import PolyCollection

_LAT = np.arange(0, 95, 5)
_X = np.array([1.0000, 0.9986, 0.9954, 0.9900, 0.9822, 0.9730, 0.9600, 0.9427, 0.9216, 0.8962,
               0.8679, 0.8350, 0.7986, 0.7597, 0.7186, 0.6732, 0.6213, 0.5722, 0.5322])
_Y = np.array([0.0000, 0.0620, 0.1240, 0.1860, 0.2480, 0.3100, 0.3720, 0.4340, 0.4958, 0.5571,
               0.6176, 0.6769, 0.7346, 0.7903, 0.8435, 0.8936, 0.9394, 0.9761, 1.0000])


def robinson(lon, lat):
    lon, lat = np.asarray(lon, float), np.asarray(lat, float)
    a = np.abs(lat)
    x = 0.8487 * np.interp(a, _LAT, _X) * np.radians(lon)
    y = 1.3523 * np.interp(a, _LAT, _Y) * np.sign(lat)
    return x, y


with open(os.path.join(EXT, "ne_110m_admin_0_countries.geojson"), encoding="utf-8") as fh:
    features = json.load(fh)["features"]
score = dict(zip(df.ISO3, df.Score))
shapes, isos = [], set()          # (area, polygon, colour); drawn largest first so enclaves stay visible
for ft in features:
    pr = ft["properties"]
    if pr["ADM0_A3"] == "ATA":
        continue
    iso = pr["ISO_A3_EH"] if pr["ISO_A3_EH"] != "-99" else pr["ADM0_A3"]
    isos.add(iso)
    geom = ft["geometry"]
    parts = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    colour = CMAP(norm(score[iso])) if iso in score else "#e6e6e6"
    for part in parts:
        ring = np.asarray(part[0])
        xy = np.column_stack(robinson(ring[:, 0], ring[:, 1]))
        area = 0.5 * abs(np.dot(xy[:, 0], np.roll(xy[:, 1], 1)) - np.dot(xy[:, 1], np.roll(xy[:, 0], 1)))
        shapes.append((area, xy, colour))
shapes.sort(key=lambda s: -s[0])
fig, ax = plt.subplots(figsize=(fs.TEXTWIDTH_IN, 3.4), layout="none")
ax.add_collection(PolyCollection([s[1] for s in shapes], facecolors=[s[2] for s in shapes],
                                 edgecolor="white", linewidth=0.3))
allxy = np.vstack([s[1] for s in shapes])
ax.set_xlim(allxy[:, 0].min(), allxy[:, 0].max()); ax.set_ylim(allxy[:, 1].min(), allxy[:, 1].max())
ax.set_aspect("equal")
# top five: country location (lon, lat) and label position in open sea (lon, lat)
