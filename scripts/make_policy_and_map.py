# number macros for the policy paragraph of Section 9.2 (typeset from this file)
def _mac(name, v):
    v = str(v)
    if v.startswith("-"):                                      # proper minus for negative numbers
        v = "\\ensuremath{-}" + v[1:]
    return "\\newcommand{\\" + name + "}{" + v + "}"
