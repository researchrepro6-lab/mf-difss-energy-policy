def fig_temporal_weights(wt: pd.DataFrame, out: Path):
    fig, axes = fs.figure(2.35, ncols=2, gridspec_kw={"width_ratios": [1, 1.6]})
    p = wt[wt.criterion.str.startswith("Policy")]
    axes[0].plot(p.year, p.weight, "o-", color=C1, label="Policy (RISE)")
    axes[0].axhline(1 / len(p), ls="--", color=CG, lw=0.8, label=rf"Uniform, $1/{len(p)}$")
    axes[0].set_title(r"(a) Policy criterion, $T_1$ (RISE reference years)")
    axes[0].set_xticks(p.year); axes[0].set_xlabel("Year"); axes[0].set_ylabel(r"Temporal weight $w^{(j)}_t$")
    axes[0].legend(loc="upper right")
    for name, col, mk, lab in [("Renewable", C2, "o", "Renewable share"), ("CO2", C3, "s", r"CO$_2$ per capita")]:
        q = wt[wt.criterion.str.contains(name)]
        axes[1].plot(q.year, q.weight, marker=mk, color=col, label=lab)
    axes[1].axhline(1 / len(ANNUAL_YEARS), ls="--", color=CG, lw=0.8, label=rf"Uniform, $1/{len(ANNUAL_YEARS)}$")
    axes[1].set_title(r"(b) Annual criteria, $T_2=T_3$")
    axes[1].set_xticks(ANNUAL_YEARS); axes[1].set_xlabel("Year"); axes[1].set_ylabel(r"Temporal weight $w^{(j)}_t$")
    axes[1].legend(loc="lower left")
    _save(fig, out)


