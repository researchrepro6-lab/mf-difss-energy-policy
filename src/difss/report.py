def fig_perturbation(pr: pd.DataFrame, out: Path):
    fig, axes = fs.figure(2.45, ncols=2)
    for name, col, mk in [("policy", C1, "o"), ("share", C2, "s"), ("co2", C3, "^")]:
        axes[0].plot(pr.delta, pr[f"max_dw_{name}"], marker=mk, color=col,
                     label={"policy": "Policy (RISE)", "share": "Renewable share", "co2": r"CO$_2$ per capita"}[name])
    axes[0].set_xlabel(r"Perturbation size $\delta$")
    axes[0].set_ylabel(r"Max. $\Vert w^{(j)}-\tilde{w}^{(j)}\Vert_1$")
    axes[0].set_title("(a) Change of the temporal weights"); axes[0].legend(loc="upper left")
    axes[1].plot(pr.delta, pr.mean_tau, "o-", color=C1, label=r"Mean Kendall’s $\tau$")
    axes[1].plot(pr.delta, pr.min_tau, "v--", color=C1, alpha=0.6, label=r"Min. Kendall’s $\tau$")
    axes[1].set_ylabel(r"Kendall’s $\tau$")
    ax2 = axes[1].twinx(); ax2.plot(pr.delta, pr.mean_top10, "s-", color=C3, label="Top-10 overlap (%)")
    ax2.set_ylim(80, 101); ax2.spines["right"].set_visible(True); ax2.set_ylabel("Top-10 overlap (%)")
    axes[1].set_xlabel(r"Perturbation size $\delta$"); axes[1].set_title("(b) Stability of the ranking")
    h1, l1 = axes[1].get_legend_handles_labels(); h2, l2 = ax2.get_legend_handles_labels()
    axes[1].legend(h1 + h2, l1 + l2, loc="lower left")
    _save(fig, out)


def fig_simulation(sim: pd.DataFrame, out: Path):
    lab = {"proposed": r"Proposed (criterion-specific $T_j$)", "interpolate": "Linear interpolation",
           "align": "Common-period alignment", "omit": "Omit sparse criteria",
           "proposed_uniform": "Proposed, uniform temporal weights"}
    col = {"proposed": C1, "proposed_uniform": C_AMBER, "interpolate": C2, "align": "#C0503F", "omit": "#7B61A8"}
    fig, axes = fs.figure(2.95, ncols=2, sharey=True)
    for k, (ax, sg) in enumerate(zip(axes, sorted(sim.sigma.unique()))):
        g = sim[sim.sigma == sg].groupby(["p_sparse", "method"]).tau.mean().unstack()
        for mth, st in [("proposed", "o-"), ("proposed_uniform", "o:"), ("interpolate", "s--"),
                        ("align", "^-."), ("omit", "x-")]:
            ax.plot(g.index, g[mth], st, color=col[mth], label=lab[mth])
        ax.set_xticks(g.index); ax.set_xlabel(r"Observations of each sparse criterion, $p_s$")
        ax.set_title(rf"({'ab'[k]}) Noise level $\sigma={sg}$")
    axes[0].set_ylabel(r"Kendall’s $\tau$ with the true ranking")
    h, l = axes[0].get_legend_handles_labels()
    fig.legend(h, l, loc="outside lower center", ncol=3)      # below the panels, clear of the curves
    _save(fig, out)
