def tex_escape(s: str) -> str:
    """Escape a label for LaTeX and typeset parameters, ranges and symbols as math."""
    s = str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")
    s = s.replace("CO2", r"CO$_2$").replace("Szmidt-Kacprzyk", "Szmidt--Kacprzyk")
    s = s.replace("min-max", "min--max").replace("pi-sensitive", r"$\pi$-sensitive")
    s = re.sub(r"(\d{4})-(\d{4})", r"\1--\2", s)                      # year ranges
    sym = {"kappa": r"\kappa", "lambda": r"\lambda", "eps": r"\varepsilon", "theta": r"\theta",
           "p1": "p_1", "q": "q", "v": "v", "m": "m"}
    s = re.sub(r"\b(kappa|lambda|eps|theta|p1|q|v|m)=([0-9.]+)",
               lambda g: "$" + sym[g.group(1)] + "=" + g.group(2) + "$", s)
    return s


