def robust_label(spec: str) -> str:
    """Display label of a sensitivity specification (LaTeX), including the
    data-definition runs whose subset size m is computed at run time."""
    if spec in ROBUST_LABEL:
        return ROBUST_LABEL[spec]
    g = re.fullmatch(r"Alternative share RE/\(RE\+fossil\), IMF dashboard \(m=(\d+)\)", spec)
    if g:
        return rf"Renewable share RE/(RE+fossil), IMF data ($m={g.group(1)}$)"
    g = re.fullmatch(r"Non-hydro renewable share \(m=(\d+)\)", spec)
    if g:
        return rf"Non-hydro renewable share ($m={g.group(1)}$)"
    if spec == "CO2 goalposts [0, 25] t":
        return r"CO$_2$ goalposts $[0,25]$ t per capita"
    g = re.fullmatch(r"Policy = RISE 2016 database, p1=1 \(m=(\d+)\)", spec)
    if g:
        return rf"Policy from the RISE 2016 database, $p_1=1$ ($m={g.group(1)}$)"
    return tex_escape(spec)


def f3(x):
    """Three decimals; a leading minus sign is typeset as a proper minus."""
    if pd.isna(x):
        return "--"
    s = f"{x:.3f}"
    return r"$-$" + s[1:] if s.startswith("-") else s


def write_table(path: Path, header: list[str], rows: list[list[str]], colspec: str):
    lines = [r"\begin{tabular}{" + colspec + "}", r"\toprule",
             " & ".join(header) + r" \\", r"\midrule"]
    for r in rows:
        if r == "MIDRULE":
            lines.append(r"\midrule")
        else:
            lines.append(" & ".join(r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


class Macros:
    def __init__(self):
        self.items = {}

    def add(self, name, value, fmt="{:.3f}"):
        assert name.isalpha(), name
        v = fmt.format(value) if not isinstance(value, str) else value
        if v.startswith("-") and v[1:2].isdigit():      # proper minus in text and math mode
            v = r"\ensuremath{-}" + v[1:]
        self.items[name] = v

    def write(self, path: Path):
        lines = ["% Auto-generated by run_all.py -- do not edit by hand"]
        for k, v in self.items.items():
            lines.append(rf"\newcommand{{\{k}}}{{{v}}}")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


